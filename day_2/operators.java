package day_2;

public class operators {
        public static void main(String[] args) {
            int a = 10;
            int b = 3;

            System.out.println(a + b);  // Arithmetic
            System.out.println(a > b);  // Relational
            System.out.println(a > 5 && b < 5); // Logical
            a += 5;                     // Assignment
            System.out.println(a);
        }
}
